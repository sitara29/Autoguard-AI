import { useEffect, useRef, useState } from "react";
import { Icon } from "../components/widgets.jsx";
import { RecList } from "../components/ResultParts.jsx";
import { STATUS_COLOR, narrative, urgency } from "../lib.js";

function requestText(result, inputs) {
  const flagged = result.components.filter((c) => c.status !== "ok").map((c) => `${c.label} (${c.status})`);
  return [
    "SERVICE REQUEST (demo, not sent anywhere)",
    `Risk level: ${result.risk_level} (risk index ${Math.round(result.risk_index)}/100)`,
    `Maintenance priority: ${result.maintenance_priority}: ${urgency(result.maintenance_priority)}`,
    `Mileage: ${Math.round(inputs.mileage_km).toLocaleString()} km · Age: ${inputs.vehicle_age_years.toFixed(1)} years`,
    `Subsystems to check: ${flagged.length ? flagged.join(", ") : "none flagged"}`,
    ...result.recommendations
      .filter((r) => r.id !== "no_advisory")
      .map((r) => `- ${r.message}`),
    "Source: research prototype trained on a synthetic dataset; not a diagnosis.",
  ].join("\n");
}

export default function Service({ result, inputs }) {
  const [open, setOpen] = useState(false);
  const [copied, setCopied] = useState(false);
  const [speaking, setSpeaking] = useState(false);
  const supported = typeof window !== "undefined" && "speechSynthesis" in window;
  const utter = useRef(null);

  useEffect(() => () => { if (supported) window.speechSynthesis.cancel(); }, [supported]);
  useEffect(() => { if (supported) window.speechSynthesis.cancel(); setSpeaking(false); }, [result, supported]);

  if (!result || !inputs) return <div className="card"><p className="placeholder">Loading…</p></div>;
  const text = narrative(result);
  const flagged = result.components.filter((c) => c.status !== "ok");
  const speak = () => {
    if (!supported) return;
    window.speechSynthesis.cancel();
    const u = new SpeechSynthesisUtterance(text);
    u.onend = () => setSpeaking(false);
    u.onerror = () => setSpeaking(false);
    utter.current = u;
    setSpeaking(true);
    window.speechSynthesis.speak(u);
  };
  const stop = () => { window.speechSynthesis.cancel(); setSpeaking(false); };
  const copy = async () => {
    try { await navigator.clipboard.writeText(requestText(result, inputs)); setCopied(true); setTimeout(() => setCopied(false), 1800); }
    catch { setCopied(false); }
  };

  return (
    <div className="cols-2">
      <div className="stack">
        <div className="card">
          <div className="card-head"><h2>Service recommendation</h2>
            <span className={`badge ${result.maintenance_priority}`}>Priority: {result.maintenance_priority}</span>
          </div>
          <div className="svc">
            <div className="svc-ico"><Icon name="calendar" size={26} /></div>
            <div>
              <div style={{ fontSize: 17, fontWeight: 600 }}>{urgency(result.maintenance_priority)}</div>
              <div className="disclaimer">
                Wording of the maintenance priority. The model does not predict a date or a cost.
              </div>
            </div>
          </div>
          <h3 style={{ margin: "16px 0 4px" }}>Subsystems to check</h3>
          <div className="chip-row">
            {flagged.length ? flagged.map((c) => (
              <span className="chip" key={c.id}>
                <span className="dot" style={{ background: STATUS_COLOR[c.status] }} />{c.label}
              </span>
            )) : <span className="disclaimer">None flagged.</span>}
          </div>
          <button className="btn" style={{ width: "100%", marginTop: 16 }} onClick={() => setOpen(true)}>
            Prepare service request (demo)
          </button>
        </div>
        <div className="card">
          <div className="card-head"><h2>Advice behind this recommendation</h2></div>
          <RecList recommendations={result.recommendations} />
        </div>
      </div>

      <div className="card">
        <div className="card-head"><h2>Read-aloud assistant (simulated)</h2>
          {speaking && <div className="wave" aria-hidden="true">{[0, 1, 2, 3, 4, 5, 6].map((i) => <i key={i} />)}</div>}
        </div>
        <div className="transcript">{text}</div>
        <div style={{ display: "flex", gap: 10, marginTop: 12 }}>
          <button className="btn" onClick={speaking ? stop : speak} disabled={!supported}>
            <span style={{ display: "inline-flex", gap: 8, alignItems: "center" }}>
              <Icon name="speaker" size={16} />{speaking ? "Stop" : "Read aloud"}
            </span>
          </button>
        </div>
        <p className="axis-note">
          {supported
            ? "Uses your browser's text-to-speech. The text is assembled from the model's output, not generated by a chatbot, and there is no microphone input."
            : "Text-to-speech is not available in this browser."}
        </p>
      </div>

      {open && (
        <div className="modal-bg" role="dialog" aria-modal="true" aria-label="Service request" onClick={() => setOpen(false)}>
          <div className="modal" onClick={(e) => e.stopPropagation()}>
            <h2>Service request summary</h2>
            <div className="callout demo">Demo only: nothing is booked or sent. Copy this summary to share it with a workshop.</div>
            <pre>{requestText(result, inputs)}</pre>
            <div style={{ display: "flex", gap: 10, justifyContent: "flex-end" }}>
              <button className="btn ghost" onClick={() => setOpen(false)}>Close</button>
              <button className="btn" onClick={copy}>{copied ? "Copied" : "Copy summary"}</button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
